"""閾値処理(Thresholding)。

数学的背景:
    閾値処理は、Grayscale画像の各ピクセル値 x に対して、しきい値
    T との大小関係だけを見て2値(0 or 255)に写す変換である。

        g(x) = 255,  x >= T
        g(x) = 0,    x <  T

    これは「ヘヴィサイドの階段関数(Heaviside step function)」

        H(y) = 1  (y >= 0)
        H(y) = 0  (y <  0)

    を使うと g(x) = 255 * H(x - T) と書ける。x = T の点で値が
    0から255へ不連続にジャンプするステップ関数であり、通常の意味では
    その点で微分が定義できない(超関数の枠組みで考えると、導関数は
    ディラックのデルタ関数 δ(x-T) になる — "しきい値のすぐ近くだけで
    無限大の変化率を持つ"というイメージ)。

    集合論的には、閾値処理は「値がT以上であるピクセルの集合
    A = [T, 255] の定義関数(indicator function, 特性関数)」

        1_A(x) = 1  (x ∈ A)
        1_A(x) = 0  (x ∉ A)

    を計算して255倍しているとも言える: g(x) = 255 * 1_{[T,255]}(x)。
    「画像を(ピクセル値の集合ではなく)ピクセル座標の集合として捉える」
    この見方は、次のトピックである二値画像処理(Erosion/Dilation)で
    本格的に使うことになる(前景ピクセルの座標集合に対する集合演算、
    として定義されるため)。

    これまで扱ってきた変換との位置づけ:
        - Grayscale変換   f(v) = w・v      : 線形写像 (R^3 -> R, 連続)
        - 明るさ/コントラスト g(x) = αx+β   : アフィン変換 (R -> R, 連続・可逆)
        - 閾値処理        g(x) = 255*H(x-T) : 非線形・不連続・非可逆

    Grayscale変換は色の情報(3次元→1次元)を失う点で不可逆だったが、
    輝度の「大小関係」自体は保存していた(単調増加関数)。閾値処理は
    その大小関係の情報すら捨て、「Tより大きいか小さいか」という
    1bitの情報だけを残す、これまでで最も情報量を落とす変換になる。
"""

import numpy as np


def apply_threshold(channel: np.ndarray, t: int) -> np.ndarray:
    """Grayscale画像を閾値 t で2値化する。

    channel: (H, W) の単一チャンネル画像 (uint8, 値域0-255)
    t: しきい値。x >= t のピクセルを255(前景)、x < t のピクセルを
       0(背景)とする(境界値 x == t は前景側に含む規約)。

    NumPyでの実装:
        `channel >= t` は要素ごとの比較演算(broadcasting)で、画像と
        同じ形状の真偽値配列(bool ndarray, True/False)を返す。これは
        ヘヴィサイド関数 H(x - t) を全ピクセルに対して同時に計算して
        いることと数学的に同値で、True=1, False=0 という対応が
        そのまま H(y)=1 (y>=0), H(y)=0 (y<0) に対応する。
        bool配列に255を掛けてuint8にキャストすることで、
        「True/Falseの配列」を「0/255の画像」に変換している。
    """
    is_foreground = channel >= t  # H(x - t) をベクトル化して一括計算
    return (is_foreground * 255).astype(np.uint8)
