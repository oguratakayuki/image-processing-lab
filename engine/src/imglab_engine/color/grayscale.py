"""RGB画像をGrayscale(輝度)画像に変換する。

数学的背景:
    RGBの3チャンネルを1チャンネルの「明るさ」に落とし込む変換であり、
    各ピクセルについて (R, G, B) ベクトルと重みベクトルの内積(加重和)を
    計算することに相当する。

        Gray = 0.299*R + 0.587*G + 0.114*B

    単純平均 (R+G+B)/3 ではなく加重平均にするのは、人間の目が緑に最も
    敏感で青に最も鈍感という知覚特性を反映するため。この重み
    (0.299, 0.587, 0.114) は ITU-R BT.601 で定義された係数で、
    3つを足すとちょうど1.0になる(=明るさのスケールを保存する)。
"""

import numpy as np

# BT.601の輝度変換係数。R, G, Bの順で1次元配列として持っておくことで、
# 画像配列の最後の軸(チャンネル軸)との内積を一度に計算できる。
_BT601_WEIGHTS = np.array([0.299, 0.587, 0.114], dtype=np.float64)


def to_grayscale(image: np.ndarray) -> np.ndarray:
    """RGB画像 (H, W, 3) uint8 を Grayscale画像 (H, W) uint8 に変換する。

    forループは使わず、NumPyの行列演算(内積)で全ピクセルをまとめて
    処理する。`image @ _BT601_WEIGHTS` は形状 (H, W, 3) の配列と
    形状 (3,) の重みベクトルの内積で、最後の軸(チャンネル軸)同士が
    畳み込まれて (H, W) になる。つまり各ピクセルについて
    R*0.299 + G*0.587 + B*0.114 を一括で計算している。
    """
    # uint8のまま加重和を計算すると桁あふれや丸め誤差の原因になるため、
    # 一旦float64に変換してから計算する。
    image_float = image.astype(np.float64)

    # (H, W, 3) と (3,) の内積 -> (H, W)
    gray_float = image_float @ _BT601_WEIGHTS

    # Quantization(量子化): 連続的な計算結果を8bit整数(0-255)の
    # 離散値に戻す。四捨五入してからuint8にキャストする。
    # (BT.601の重みの合計は1.0なので、入力が0-255の範囲であれば
    # 出力も0-255に収まり、クリップ処理は不要)
    return np.round(gray_float).astype(np.uint8)
