"""平行移動(Translation)。

数学的背景:
    平行移動は、座標(x, y)をベクトル(tx, ty)だけずらす変換である。

        (x, y) -> (x + tx, y + ty)

    これをそのまま「入力側から出力側へ」実装すること(順方向マッピング,
    forward mapping)もできるが、画像処理では代わりに「出力側から
    入力側を逆算する」逆方向マッピング(inverse mapping)が標準的に
    使われる。

    順方向マッピングの問題点:
        入力画像の各点(x, y)について、変換後の位置(x+tx, y+ty)に
        値を書き込んでいく方式。平行移動のように整数シフトしかしない
        変換では問題にならないが、後続の回転・拡大縮小では変換後の
        座標が整数になるとは限らない(例: 30度回転すると、整数座標は
        一般に非整数座標に写る)。非整数の書き込み先を四捨五入すると、
        出力側で「どの入力からも書き込まれない穴(ピクセル抜け)」が
        発生しうる。

    逆方向マッピングの考え方:
        出力画像の各点(out_y, out_x)について、「この点に写ってくる
        入力画像上の点はどこか」を、変換の逆変換で逆算し、そこから
        値を持ってくる方式。出力側を1ピクセルずつ漏れなく埋めていく
        ため、穴が発生しない。

        平行移動の逆変換は、符号を反転するだけでよい。

            out(out_x, out_y) = in(out_x - tx, out_y - ty)

        このモジュールでは、今後の回転・拡大縮小でも使い回せるよう、
        最初からこの逆方向マッピングの構造で実装する。

    境界の扱い:
        逆算した入力側の座標が画像の範囲外になる場合(画像の端が
        はみ出す/画像の外側から新しい領域が現れる場合)は、
        畳み込み・モルフォロジー演算で採用したゼロパディングと同じ
        考え方で、0(黒)で埋める。
"""

import numpy as np


def translate(image: np.ndarray, tx: int, ty: int) -> np.ndarray:
    """画像を(tx, ty)だけ平行移動する(逆方向マッピング)。

    前提条件:
        imageは(H, W)のGrayscale画像、または(H, W, 3)のRGB画像の
        どちらでもよい(色の値そのものには一切手を加えず、座標だけを
        動かす変換のため、1-1のGrayscale変換のような色の計算は
        不要)。

    Args:
        image: 平行移動する画像。(H, W)または(H, W, 3)のuint8配列。
        tx: x方向(横方向、列方向)の移動量(ピクセル)。正の値で右に
            移動する。
        ty: y方向(縦方向、行方向)の移動量(ピクセル)。正の値で下に
            移動する。

    Returns:
        平行移動後の画像。入力と同じ形状・dtype。画像の端からはみ
        出した部分は切り捨てられ、新しく現れた部分は0(黒)で埋め
        られる。
    """
    # image.shape は、(H, W) なら (高さ, 幅) の2要素タプル、
    # (H, W, 3) なら (高さ, 幅, チャンネル数) の3要素タプル。
    # [:2] というスライスで、どちらの場合でも先頭2要素(高さ・幅)
    # だけを取り出せる(Grayscale/RGB両対応にするための書き方)。
    height, width = image.shape[:2]

    # np.zeros_like(image) は、imageと「同じ形状(shape)・同じ型
    # (dtype)」の配列を新しく作り、全要素を0で埋めて返すNumPyの
    # 関数。(H, W)画像なら2次元、(H, W, 3)画像なら3次元の配列に
    # なり、どちらの場合も自動的に対応できる。
    # まず全体を0(黒)にしておき、逆算で入力が見つかった場所だけ
    # 後から値を上書きする、という組み立て方にしている。
    output = np.zeros_like(image)

    for out_y in range(height):
        for out_x in range(width):
            # 逆方向マッピング: 出力の点(out_y, out_x)に写ってくる
            # 入力側の点を、平行移動の逆変換(符号反転)で逆算する。
            src_y = out_y - ty
            src_x = out_x - tx

            # 入力座標は実際に画像の中に存在するかどうか。
            # Pythonの比較演算子は 0 <= src_y < height のように
            # 連続して書くと「0 <= src_y かつ src_y < height」という
            # 意味になる(Ruby/PHPにはない書き方)。
            if 0 <= src_y < height and 0 <= src_x < width:
                # 範囲内なら、入力画像のその位置の値(Grayscaleなら
                # 輝度1つ、RGBならR,G,Bの3つ)をそのままコピーする。
                output[out_y, out_x] = image[src_y, src_x]
            # 範囲外(画像の外からはみ出してきた/新しく現れた部分)
            # なら、outputはすでに0で初期化済みなので何もしない。

    return output
